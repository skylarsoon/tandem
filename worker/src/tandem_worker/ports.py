"""Application ports, not vendor SDK calls or additional REST endpoints."""
from __future__ import annotations

import time
from typing import Protocol

from .contracts import Brief, Candidate, Claim, Decision, Explanation, Message, Question, Snapshot, SolverResult, ValidationReport, VoiceDraft


class Clock(Protocol):
    def now(self) -> float: ...


class SystemClock:
    def now(self) -> float:
        return time.time()


class FakeClock:
    def __init__(self, value: float = 1_800_000_000):
        self.value = value

    def now(self) -> float:
        return self.value

    def advance(self, seconds: float) -> None:
        self.value += seconds


class BackendPort(Protocol):
    def claim_job(self, job_id: str, worker_id: str, request_key: str) -> Claim: ...
    def load_execution_context(self, claim: Claim) -> Snapshot: ...
    def renew_lease(self, claim: Claim) -> None: ...
    def submit_agent_message(self, claim: Claim, message: Message, participants: tuple[str, ...]) -> str: ...
    def record_message_processed(self, claim: Claim, message_id: str, recipient: str, replies: tuple[str, ...]) -> None: ...
    def ask_owner(self, claim: Claim, question: Question) -> str: ...
    def answer_question(self, owner: str, question_id: str, version: int, answer: bool, request_key: str) -> str: ...
    def park_job(self, claim: Claim, question_refs: list[str]) -> None: ...
    def schedule_resume(self, job_id: str) -> bool: ...
    def publish_proposal(self, claim: Claim, selected: tuple[str, ...], candidates: list[Candidate], report: ValidationReport, key: str,
                         explanation: Explanation | None = None) -> str: ...
    # Owner-only agent note (e.g. why no plan fits them) and a neutral room event.
    def notify_owner(self, claim: Claim, owner: str, text: str, key: str) -> None: ...
    def room_event(self, claim: Claim, kind: str, payload: dict, key: str) -> None: ...
    def finish_job(self, claim: Claim, outcome: str) -> None: ...
    def fail_job(self, claim: Claim, code: str) -> None: ...
    # Scoped reads/operation receipts implemented through authorized projections.
    def read_brief(self, claim: Claim, owner: str) -> Brief: ...
    def get_question(self, claim: Claim, question_id: str) -> Question: ...
    def check(self, claim: Claim) -> None: ...
    def operation(self, claim: Claim, key: str, request: dict, kind: str, function): ...
    def store_candidates(self, claim: Claim, candidates: list[Candidate]) -> None: ...
    def reusable_candidates(self, claim: Claim) -> list[Candidate]: ...
    def has_permission(self, claim: Claim, owner: str, kind: str, action_ref: str) -> bool: ...
    def close_threads(self, claim: Claim, reason: str) -> None: ...
    def eligible_jobs(self) -> list[str]: ...


class ModelPort(Protocol):
    def decide(self, context: dict) -> Decision: ...
    def voice(self, context: dict) -> VoiceDraft: ...


class ResearchPort(Protocol):
    def search(self, request: dict) -> list[Candidate]: ...


class SolverPort(Protocol):
    def solve(self, snapshot: Snapshot, briefs: list[Brief], candidates: list[Candidate]) -> SolverResult: ...


class ValidatorPort(Protocol):
    def validate(self, snapshot: Snapshot, briefs: list[Brief], candidates: list[Candidate], selected: tuple[str, ...], now: float) -> ValidationReport: ...
